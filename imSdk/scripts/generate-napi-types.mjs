// entry/scripts/generate-napi-types.mjs
import fs from 'fs';
import path from 'path';
import { globSync } from 'glob';

const CPP_DIR = '../src/main/cpp';
const OUTPUT_DTS = '../src/main/cpp/types/libimsdk/index.d.ts';
const COMMENT_TAG = '@napi-ts:';

/**
 * 解析单行注释 // @napi-ts: ...
 */
function parseSingleLineComment(line) {
  const trimmed = line.trim();
  if (!trimmed.startsWith('//') || !trimmed.includes(COMMENT_TAG)) return null;

  let decl = trimmed
    .replace(/^\/\/\s*/, '')
    .replace(COMMENT_TAG, '')
    .trim();

  if ((decl.startsWith('export ') || decl.startsWith('function ')) && !decl.endsWith(';')) {
    decl += ';';
  }

  if (decl.startsWith('export ') || decl.startsWith('function ')) {
    return { jsdoc: '', signature: decl };
  }
  return null;
}

function parseBlockComment(block) {
  const match = block.match(/\/\*\s*@napi-ts([\s\S]*?)\*\//);
  if (!match) return null;

  const content = match[1].trim();
  const lines = content.split('\n').map(l => l.trim());

  let description = [];
  const params = [];
  let returns = '';
  let throwsDesc = ''; // 👈 新增：用于存储 @throws 描述
  let signature = '';

  for (let line of lines) {
    if (line.startsWith('@param ')) {
      params.push(line.substring(7).trim());
    } else if (line.startsWith('@returns ')) {
      returns = line.substring(9).trim();
    } else if (line.startsWith('@throws ')) { // 👈 新增处理 @throws
      throwsDesc = line.substring(8).trim(); // 跳过 "@throws "
    } else if (line.startsWith('@signature ')) {
      signature = line.substring(11).trim();
      if (!signature.endsWith(';')) signature += ';';
    } else if (!line.startsWith('@') && line) {
      description.push(line);
    }
    // 忽略其他未知标签（如 @example 可后续扩展）
  }

  if (!signature) return null;

  // 构建 JSDoc
  let jsdoc = '/**\n';
  if (description.length > 0) {
    jsdoc += ' * ' + description.join('\n * ') + '\n';
  }
  for (const param of params) {
    jsdoc += ` * @param ${param}\n`;
  }
  if (returns) {
    jsdoc += ` * @returns ${returns}\n`;
  }
  if (throwsDesc) { // 👈 如果有 @throws，加入 JSDoc
    jsdoc += ` * @throws ${throwsDesc}\n`;
  }
  jsdoc += ' */';

  return { jsdoc, signature };
}

/**
 * 从文件内容提取所有 NAPI 声明
 */
function extractDeclarations(content) {
  const items = [];

  // 1. 匹配块注释 /*@napi-ts ... */
  const blockRegex = /\/\*\s*@napi-ts[\s\S]*?\*\//g;
  let blockMatch;
  while ((blockMatch = blockRegex.exec(content)) !== null) {
    const item = parseBlockComment(blockMatch[0]);
    if (item) items.push(item);
  }

  // 2. 扫描单行注释 // @napi-ts:
  const lines = content.split('\n');
  for (const line of lines) {
    const item = parseSingleLineComment(line);
    if (item) items.push(item);
  }

  return items;
}

/**
 * 主函数
 */
function main() {
  console.log('🔍 [NAPI-TS] Scanning C++ files...');

  const patterns = ['**/*.cpp', '**/*.cc'];
  const allItems = [];

  for (const pattern of patterns) {
    const files = globSync(path.join(CPP_DIR, pattern), { nodir: true });
    for (const file of files) {
      const content = fs.readFileSync(file, 'utf8');
      const items = extractDeclarations(content);
      if (items.length > 0) {
        console.log(`✅ Extracted ${file} → ${items.length} declarations`);
        allItems.push(...items);
      }
    }
  }

  if (allItems.length === 0) {
    console.warn('⚠️ [NAPI-TS] No @napi-ts comments found');
    return;
  }

  // 按 signature 去重
  const uniqueItems = [];
  const seen = new Set();
  for (const item of allItems) {
    if (!seen.has(item.signature)) {
      seen.add(item.signature);
      uniqueItems.push(item);
    }
  }

  const dtsContent = `// Auto-generated by generate-napi-types.mjs
// DO NOT EDIT MANUALLY

${uniqueItems.map(item =>
  item.jsdoc ? `${item.jsdoc}\n${item.signature}` : item.signature
).join('\n\n')}
`;

  const outDir = path.dirname(OUTPUT_DTS);
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }
  fs.writeFileSync(OUTPUT_DTS, dtsContent, 'utf8');
  console.log(`✅ [NAPI-TS] Generated: ${OUTPUT_DTS}`);
}

main();